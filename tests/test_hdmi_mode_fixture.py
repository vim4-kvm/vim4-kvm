"""A source backing-raster change must never qualify an unchanged HDMI input."""
import importlib.util
import ctypes
import errno
import json
from pathlib import Path
import struct
import tempfile
import unittest
from unittest.mock import patch
from board.vim4vrr import cta_blocks, validate

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    'hdmi_mode_fixture', ROOT / 'packaging/kernel-edge/hdmi-mode-fixture.py')
fixture = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fixture)


def receiver_bytes(mode):
    raw = bytearray(132)
    polarities = int(mode['vsync_positive']) | int(mode['hsync_positive']) << 1
    struct.pack_into('=5IQ6I', raw, 0, 0, mode['width'], mode['height'], 0,
                     polarities, mode['pixelclock'], mode['hfrontporch'], mode['hsync'],
                     mode['hbackporch'], mode['vfrontporch'], mode['vsync'], mode['vbackporch'])
    return raw


def decode_dtd(data):
    width = data[2] | (data[4] >> 4) << 8
    height = data[5] | (data[7] >> 4) << 8
    hblank = data[3] | (data[4] & 15) << 8
    vblank = data[6] | (data[7] & 15) << 8
    clock = int.from_bytes(data[:2], 'little') * 10000
    return width, height, clock / ((width + hblank) * (height + vblank))


class HDMIInputModeTest(unittest.TestCase):
    def test_withdrawn_edid_is_queried_without_requesting_nonexistent_blocks(self):
        def ioctl(fd, command, request):
            if request.blocks:
                raise OSError(errno.ENODATA, 'No data available')
            request.blocks = 0
        with patch.object(fixture.os, 'open', return_value=7), \
                patch.object(fixture.os, 'close'), \
                patch.object(fixture.fcntl, 'ioctl', side_effect=ioctl) as query:
            self.assertEqual(fixture.read_edid('/dev/video0'), b'')
        self.assertEqual(query.call_count, 1)

    def test_published_edid_reads_the_queried_block_count(self):
        data = fixture.BASELINE.read_bytes()
        def ioctl(fd, command, request):
            if request.blocks == 0:
                request.blocks = len(data) // 128
            else:
                self.assertEqual(request.blocks, len(data) // 128)
                ctypes.memmove(request.edid, data, len(data))
        with patch.object(fixture.os, 'open', return_value=7), \
                patch.object(fixture.os, 'close'), \
                patch.object(fixture.fcntl, 'ioctl', side_effect=ioctl):
            self.assertEqual(fixture.read_edid('/dev/video0'), data)

    def test_query_decodes_the_actual_linux_uapi_structure(self):
        # Generated by C from the pinned Linux V4L2 timing initializer, rather
        # than by this Python decoder. Guard packing, clock offset and ioctl.
        recorded = json.loads((ROOT / 'tests/fixtures/hdmi-uhd60-dv-timings.json').read_text())
        self.assertEqual(fixture.QUERY_DV_TIMINGS, recorded['query_ioctl'])
        measured = fixture.decode_timings(bytes.fromhex(recorded['raw_hex']))
        self.assertEqual((measured['width'], measured['height']), (3840, 2160))
        self.assertEqual(measured['pixelclock'], 594000000)
        self.assertEqual(measured['hz'], 60)

    def test_backing_switch_cannot_qualify_an_unchanged_uhd_wire(self):
        modes = fixture.load_modes()
        requested = next(m for m in modes if (m['width'], m['height']) == (800, 600))
        wire = next(m for m in modes if m['id'] == 18)

        def ioctl(fd, request, raw):
            raw[:] = receiver_bytes(wire)

        with patch.object(fixture.sys, 'platform', 'linux'), \
                patch.object(fixture.os, 'open', return_value=7), \
                patch.object(fixture.os, 'close') as close, \
                patch.object(fixture.fcntl, 'ioctl', side_effect=ioctl):
            measured = fixture.measure('/dev/video0')
        close.assert_called_once_with(7)
        # Window M had a successful 800x600 CoreGraphics mode ID, while this
        # independent receiver measurement and browser both remained UHD60.
        with self.assertRaisesRegex(ValueError, 'backing dimensions are insufficient'):
            fixture.qualify(requested, measured)

    def test_single_dtd_fixtures_force_requested_timing_and_preserve_audio(self):
        with tempfile.TemporaryDirectory() as temporary:
            folder = Path(temporary) / 'fixtures'
            fixture.prepare(folder)
            modes = json.loads((folder / 'modes.json').read_text())
            serials = set()
            for mode in modes:
                with self.subTest(mode=mode['id']):
                    edid = (folder / (str(mode['id']) + '.bin')).read_bytes()
                    validate(edid)
                    width, height, hz = decode_dtd(edid[54:72])
                    self.assertEqual((width, height), (mode['width'], mode['height']))
                    actual = fixture.decode_timings(receiver_bytes(mode))
                    self.assertLess(abs(actual['hz'] - hz), .05)
                    self.assertEqual(fixture.qualify(mode, actual)['mode_id'], mode['id'])
                    self.assertFalse(any(edid[35:38]))
                    self.assertEqual(edid[38:54], bytes((1, 1)) * 8)
                    for offset in (72, 90, 108):
                        self.assertEqual(edid[offset:offset + 2], bytes(2))
                    blocks, start = cta_blocks(edid[128:])
                    self.assertTrue(any(tag == 1 for tag, payload in blocks))
                    self.assertFalse(any(tag == 2 for tag, payload in blocks))
                    self.assertFalse(any(edid[128 + start:255]))
                    serials.add(edid[12:16])
            self.assertEqual(len(serials), len(modes))

    def test_same_geometry_with_wrong_refresh_is_rejected(self):
        mode = fixture.load_modes()[-1]
        measured = fixture.decode_timings(receiver_bytes(mode))
        measured['hz'] *= .9999  # Fractional measurement and EDID clock rounding.
        fixture.qualify(mode, measured)
        measured['hz'] /= 2
        with self.assertRaisesRegex(ValueError, 'HDMI input'):
            fixture.qualify(mode, measured)

    def test_unqualified_input_and_failed_query_do_not_produce_a_pass(self):
        with self.assertRaisesRegex(ValueError, 'no qualified input'):
            fixture.decode_timings(bytes(132))
        with patch.object(fixture.sys, 'platform', 'linux'), \
                patch.object(fixture.os, 'open', return_value=9), \
                patch.object(fixture.os, 'close') as close, \
                patch.object(fixture.fcntl, 'ioctl', side_effect=BlockingIOError):
            with self.assertRaises(BlockingIOError):
                fixture.measure('/dev/video0')
        close.assert_called_once_with(9)


if __name__ == '__main__':
    unittest.main()
